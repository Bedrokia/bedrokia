namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a thunderstorm starts or stops.
/// </summary>
public sealed class ThunderChangeEvent : CancellableEvent
{
    public bool Thundering { get; }
    public int DurationTicks { get; set; }

    public ThunderChangeEvent(bool thundering, int durationTicks)
    {
        Thundering = thundering;
        DurationTicks = durationTicks;
    }
}
