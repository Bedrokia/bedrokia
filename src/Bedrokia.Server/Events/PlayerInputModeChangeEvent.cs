using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a player switches input mode (mouse/keyboard, touch, gamepad, etc.).
/// </summary>
public sealed class PlayerInputModeChangeEvent(BedrockConnection player, uint oldMode, uint newMode) : IPlayerEvent
{
    /// <summary>The player whose input mode changed.</summary>
    public BedrockConnection Player { get; } = player;

    /// <summary>Uniform player accessor.</summary>
    public BedrockConnection player() => Player;

    /// <summary>The previous input mode ID.</summary>
    public uint OldMode { get; } = oldMode;

    /// <summary>The new input mode ID.</summary>
    public uint NewMode { get; } = newMode;
}

