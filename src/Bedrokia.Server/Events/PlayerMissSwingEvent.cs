using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a player left-clicks into empty air without hitting a block or entity.
/// </summary>
public sealed class PlayerMissSwingEvent(BedrockConnection player) : CancellableEvent, IPlayerEvent
{
    /// <summary>The player who swung their arm in the air.</summary>
    public BedrockConnection Player { get; } = player;

    /// <summary>Uniform player accessor.</summary>
    public BedrockConnection player() => Player;
}

