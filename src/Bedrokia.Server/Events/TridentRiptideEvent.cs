using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a player uses a trident with the riptide enchantment.
/// </summary>
public sealed class TridentRiptideEvent : CancellableEvent
{
    public BedrockConnection Player { get; }
    public float Strength { get; set; }

    public TridentRiptideEvent(BedrockConnection player, float strength)
    {
        Player = player;
        Strength = strength;
    }
}
