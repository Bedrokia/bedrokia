using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when an open container window is closed for a player.
/// </summary>
public sealed class ContainerCloseEvent
{
    public BedrockConnection Player { get; }
    public byte WindowId { get; }

    public ContainerCloseEvent(BedrockConnection player, byte windowId)
    {
        Player = player;
        WindowId = windowId;
    }
}
