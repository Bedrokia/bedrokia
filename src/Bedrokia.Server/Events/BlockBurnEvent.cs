using Bedrokia.Server.Game;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a block is destroyed by fire.
/// If cancelled, the block is not burned.
/// </summary>
public sealed class BlockBurnEvent : CancellableEvent
{
    public BlockPos Position { get; }
    public BlockType Block { get; }

    public BlockBurnEvent(BlockPos position, BlockType block)
    {
        Position = position;
        Block = block;
    }
}
