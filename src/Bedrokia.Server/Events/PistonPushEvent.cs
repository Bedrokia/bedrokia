using Bedrokia.Server.Game;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when an extending piston pushes attached blocks.
/// </summary>
public sealed class PistonPushEvent : CancellableEvent
{
    public BlockPos Pos { get; }
    public List<BlockPos> AttachedBlocks { get; }

    public PistonPushEvent(BlockPos pos, List<BlockPos> attachedBlocks)
    {
        Pos = pos;
        AttachedBlocks = attachedBlocks;
    }
}
