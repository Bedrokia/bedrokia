using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a player blocks an attack with a shield.
/// </summary>
public sealed class ShieldBlockEvent : CancellableEvent, IPlayerEvent{
    public BedrockConnection Player { get; }
    public string Attacker { get; }
    public float Damage { get; }

    public ShieldBlockEvent(BedrockConnection player, string attacker, float damage)
    {
        Player = player;
        Attacker = attacker;
        Damage = damage;
    }
}
