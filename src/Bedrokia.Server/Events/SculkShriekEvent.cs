using Bedrokia.Server.Game;
using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a sculk shrieker warns or activates.
/// </summary>
public sealed class SculkShriekEvent : CancellableEvent
{
    public BedrockConnection Player { get; }
    public BlockPos Pos { get; }
    public int WarningLevel { get; set; }

    public SculkShriekEvent(BedrockConnection player, BlockPos pos, int warningLevel)
    {
        Player = player;
        Pos = pos;
        WarningLevel = warningLevel;
    }
}
