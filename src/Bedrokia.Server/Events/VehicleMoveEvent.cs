using System.Numerics;
using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a vehicle driven by a player moves.
/// </summary>
public sealed class VehicleMoveEvent : CancellableEvent, IPlayerEvent{
    public BedrockConnection Player { get; }
    public ulong VehicleEntityId { get; }
    public Vector3 Position { get; }

    public VehicleMoveEvent(BedrockConnection player, ulong vehicleEntityId, Vector3 position)
    {
        Player = player;
        VehicleEntityId = vehicleEntityId;
        Position = position;
    }
}
