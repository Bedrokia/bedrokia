using Bedrokia.Server.Entities;
using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a player shears a sheep.
/// If cancelled, the sheep is not sheared and drops no wool.
/// </summary>
public sealed class SheepShearEvent(BedrockConnection player, Mob sheep) : CancellableEvent, IPlayerEvent
{
    /// <summary>The player shearing the sheep.</summary>
    public BedrockConnection Player { get; } = player;

    /// <summary>Uniform player accessor.</summary>
    public BedrockConnection player() => Player;

    /// <summary>The sheared sheep mob.</summary>
    public Mob Sheep { get; } = sheep;
}

