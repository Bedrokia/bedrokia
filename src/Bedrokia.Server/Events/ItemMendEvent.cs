using Bedrokia.Server.Game;
using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when an item with mending is repaired by experience.
/// </summary>
public sealed class ItemMendEvent : CancellableEvent
{
    public BedrockConnection Player { get; }
    public ItemStack Item { get; }
    public int RepairAmount { get; set; }

    public ItemMendEvent(BedrockConnection player, ItemStack item, int repairAmount)
    {
        Player = player;
        Item = item;
        RepairAmount = repairAmount;
    }
}
