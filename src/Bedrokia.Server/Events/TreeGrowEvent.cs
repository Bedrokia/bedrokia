using Bedrokia.Server.Game;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a sapling grows into a tree.
/// </summary>
public sealed class TreeGrowEvent : CancellableEvent
{
    public BlockPos Pos { get; }
    public uint SaplingBlockId { get; }

    public TreeGrowEvent(BlockPos pos, uint saplingBlockId)
    {
        Pos = pos;
        SaplingBlockId = saplingBlockId;
    }
}
