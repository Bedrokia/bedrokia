using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when an in-game player runs a command.
/// If cancelled, the command execution is aborted.
/// </summary>
public sealed class PlayerCommandEvent : CancellableEvent, IPlayerEvent{
    public BedrockConnection Player { get; }
    public string CommandLine { get; set; }

    public PlayerCommandEvent(BedrockConnection player, string commandLine)
    {
        Player = player;
        CommandLine = commandLine;
    }
}
