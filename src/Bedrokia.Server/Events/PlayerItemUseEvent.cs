using Bedrokia.Server.Game;
using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>Fired when a player right-clicks in the air with an item in hand (before eating, throwing...).</summary>
public sealed class PlayerItemUseEvent(BedrockConnection player, ItemStack item) : CancellableEvent
{
    public BedrockConnection Player => player;
    public ItemStack Item => item;
}
