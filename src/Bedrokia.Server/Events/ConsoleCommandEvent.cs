namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a command is executed from the server console.
/// If cancelled, the command is not executed.
/// </summary>
public sealed class ConsoleCommandEvent(string commandLine) : CancellableEvent
{
    /// <summary>The command line entered into the console, including arguments.</summary>
    public string CommandLine { get; set; } = commandLine;
}

