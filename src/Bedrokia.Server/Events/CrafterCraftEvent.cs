using Bedrokia.Server.Game;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when an automated Crafter block crafts and dispenses an item.
/// </summary>
public sealed class CrafterCraftEvent : CancellableEvent
{
    public BlockPos Pos { get; }
    public ItemStack Result { get; set; }

    public CrafterCraftEvent(BlockPos pos, ItemStack result)
    {
        Pos = pos;
        Result = result;
    }
}
