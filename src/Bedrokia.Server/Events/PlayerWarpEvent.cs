using System.Numerics;
using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a player is warped/teleported via ender pearl, chorus fruit, command, or plugin.
/// </summary>
public sealed class PlayerWarpEvent : CancellableEvent, IPlayerEvent{
    public BedrockConnection Player { get; }
    public string Cause { get; }
    public Vector3 Destination { get; set; }

    public PlayerWarpEvent(BedrockConnection player, string cause, Vector3 destination)
    {
        Player = player;
        Cause = cause;
        Destination = destination;
    }
}
