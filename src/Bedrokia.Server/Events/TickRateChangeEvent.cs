namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when the server tick rate or freeze state is modified.
/// </summary>
public sealed class TickRateChangeEvent : CancellableEvent
{
    public float Rate { get; set; }
    public bool Frozen { get; set; }

    public TickRateChangeEvent(float rate, bool frozen)
    {
        Rate = rate;
        Frozen = frozen;
    }
}
