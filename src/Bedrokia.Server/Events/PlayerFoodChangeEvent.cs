using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a player's food level or saturation changes.
/// </summary>
public sealed class PlayerFoodChangeEvent : CancellableEvent, IPlayerEvent{
    public BedrockConnection Player { get; }
    public int OldFood { get; }
    public int Food { get; set; }
    public float Saturation { get; set; }

    public PlayerFoodChangeEvent(BedrockConnection player, int oldFood, int food, float saturation)
    {
        Player = player;
        OldFood = oldFood;
        Food = food;
        Saturation = saturation;
    }
}
