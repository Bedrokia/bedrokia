using Bedrokia.Server.Game;
using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a player drops an item (via drop key Q or dropping from inventory).
/// If cancelled, the item is not dropped and stays in the player's inventory.
/// </summary>
public sealed class PlayerDropItemEvent(BedrockConnection player, ItemStack item) : CancellableEvent
{
    public BedrockConnection Player => player;
    public ItemStack Item => item;
}
