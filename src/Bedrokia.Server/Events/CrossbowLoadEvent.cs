using Bedrokia.Server.Game;
using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a player finishes loading a crossbow with ammo.
/// </summary>
public sealed class CrossbowLoadEvent : CancellableEvent
{
    public BedrockConnection Player { get; }
    public ItemStack Ammo { get; }

    public CrossbowLoadEvent(BedrockConnection player, ItemStack ammo)
    {
        Player = player;
        Ammo = ammo;
    }
}
