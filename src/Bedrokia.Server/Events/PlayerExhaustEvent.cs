using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when exhaustion points are added to a player.
/// If cancelled, exhaustion points are not added.
/// </summary>
public sealed class PlayerExhaustEvent(BedrockConnection player, float amount) : CancellableEvent, IPlayerEvent
{
    /// <summary>The player receiving exhaustion.</summary>
    public BedrockConnection Player { get; } = player;

    /// <summary>Uniform player accessor.</summary>
    public BedrockConnection player() => Player;

    /// <summary>The exhaustion points added; can be modified.</summary>
    public float Amount { get; set; } = amount;
}

