using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a player attacks an entity (player, mob, or custom entity).
/// If cancelled, the attack is aborted.
/// </summary>
public sealed class PlayerAttackEvent(BedrockConnection player, long targetEntityId, float damage) : CancellableEvent, IPlayerEvent
{
    /// <summary>The attacking player.</summary>
    public BedrockConnection Player { get; } = player;

    /// <summary>Uniform player accessor.</summary>
    public BedrockConnection player() => Player;

    /// <summary>The entity runtime ID of the target being attacked.</summary>
    public long TargetEntityId { get; } = targetEntityId;

    /// <summary>Base attack damage before entity-specific modifiers; can be modified.</summary>
    public float Damage { get; set; } = damage;
}

