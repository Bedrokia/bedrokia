using Bedrokia.Server.Game;
using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when an item's durability reaches zero and breaks (non-cancellable post-action).
/// </summary>
public sealed class ItemBreakEvent
{
    public BedrockConnection Player { get; }
    public int Slot { get; }
    public ItemStack Item { get; }

    public ItemBreakEvent(BedrockConnection player, int slot, ItemStack item)
    {
        Player = player;
        Slot = slot;
        Item = item;
    }
}
