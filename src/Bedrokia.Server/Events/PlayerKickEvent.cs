using Bedrokia.Server.Network;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a player is kicked from the server.
/// If cancelled, the disconnection is aborted.
/// </summary>
public sealed class PlayerKickEvent(BedrockConnection player, string reason) : CancellableEvent, IPlayerEvent
{
    /// <summary>The player being kicked.</summary>
    public BedrockConnection Player { get; } = player;

    /// <summary>Uniform player accessor.</summary>
    public BedrockConnection player() => Player;

    /// <summary>The kick reason shown to the player; can be modified.</summary>
    public string Reason { get; set; } = reason;
}

