using Bedrokia.Server.Game;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a newly generated chunk finishes terrain population.
/// </summary>
public sealed class ChunkPopulateEvent(World world, Chunk chunk)
{
    /// <summary>The world containing the chunk.</summary>
    public World World { get; } = world;

    /// <summary>The populated chunk.</summary>
    public Chunk Chunk { get; } = chunk;
}

