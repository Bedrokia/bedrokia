using Bedrokia.Server.Entities;

namespace Bedrokia.Server.Events;

/// <summary>
/// Fired when a sheared sheep regrows its wool after eating grass.
/// If cancelled, the wool is not regrown.
/// </summary>
public sealed class SheepRegrowWoolEvent(Mob sheep) : CancellableEvent
{
    /// <summary>The sheep regrowing wool.</summary>
    public Mob Sheep { get; } = sheep;
}

